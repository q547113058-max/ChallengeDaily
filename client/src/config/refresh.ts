// ── 数据刷新节奏统一配置 ──
//
// 背景：原先各页面刷新间隔散落各处（30s / 60s / 无），用户会感觉"有的页面会自动更新、
// 有的必须手动刷新"。此处集中定义，所有数据轮询统一引用。
//
// 注意：以下场景**不使用**这些常量，各自保持原值：
//   - AI 调用类（深度画像洞察、情绪关怀）：成本高，5 分钟
//   - 多窗口状态同步（clientState）：15 秒，与业务数据无关
//   - 断线重连倒计时（shared.tsx）：1 秒
//   - 审批弹窗倒计时（TodoApprovalToast）：1 秒
//   - 设置页的"截图间隔"：用户可配置项，非刷新节奏

/** 业务数据统一刷新间隔（毫秒）。页面可见时生效，隐藏时暂停。 */
export const DATA_REFRESH_MS = 30_000

/** AI 类接口刷新间隔（毫秒）——调用有成本，刻意放慢 */
export const AI_REFRESH_MS = 300_000
